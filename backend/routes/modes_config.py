
# ========== 向量库配置 ==========
VECTOR_CONFIG = {
    "enabled": True,  # 默认开启
    "path": "/opt/kanban-react/Files/sds1/core/vector_index",
    "top_k": 3,  # 检索Top3文档
    "max_length": 1000,  # 单文档最大长度
}

def retrieve_from_vector_db(query: str, top_k: int = None) -> list:
    """从向量库检索相关文档"""
    if not VECTOR_CONFIG["enabled"]:
        return []

    try:
        import os
        import json

        # 简单的关键词匹配（实际应使用向量检索）
        # 读取索引文件
        index_file = os.path.join(VECTOR_CONFIG["path"], "index.json")
        if not os.path.exists(index_file):
            return []

        with open(index_file) as f:
            docs = json.load(f)

        # 关键词匹配
        query_lower = query.lower()
        matches = []
        for doc in docs:
            score = 0
            content = doc.get("content", "")
            # 简单TF-IDF风格匹配
            for word in query_lower.split():
                if word in content.lower():
                    score += 1
            if score > 0:
                matches.append({"score": score, "doc": doc})

        # 排序取TopK
        matches.sort(key=lambda x: x["score"], reverse=True)
        top_k = top_k or VECTOR_CONFIG["top_k"]

        result = []
        for m in matches[:top_k]:
            content = m["doc"].get("content", "")[:VECTOR_CONFIG["max_length"]]
            result.append({
                "title": m["doc"].get("title", "未命名文档"),
                "content": content,
                "score": m["score"]
            })
        return result
    except Exception as e:
        print(f"Vector DB retrieval error: {e}")
        return []

