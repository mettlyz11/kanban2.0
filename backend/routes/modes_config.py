# ========== 自动选择规则 ==========
def auto_select_mode(question: str, mode_type: str = "chat") -> str:
    """根据问题内容自动选择最适合的策略"""
    q = question.lower()

    # 脑风暴模式关键词
    if mode_type == "brainstorm":
        if any(k in q for k in ["辩", "对立", "冲突", "正反", "优劣", "利弊", "vs", "对比"]):
            return "debate"
        elif any(k in q for k in ["合", "协作", "一起", "共同", "互补", "配合"]):
            return "collab"
        else:
            return "mentor"

    # 单聊/通用模式关键词
    keywords_map = {
        "optimize": ["优化", "改进", "提升", "效率", "性能", "瓶颈"],
        "troubleshoot": ["危机", "紧急", "事故", "故障", "风险", "问题", "bug", "错误"],
        "growth": ["增长", "获客", "流量", "转化", "营销", "推广"],
        "plan": ["规划", "计划", "路线图", "里程碑", "目标", "roadmap"],
        "research": ["调研", "研究", "调查", "分析", "了解", "查查"],
        "evaluate": ["评估", "评价", "怎么样", "好不好", "可行", "值得"],
        "learn": ["学习", "了解", "入门", "科普", "解释", "什么是", "怎么"],
        "brainstorm": ["创意", "想法", "方案", "怎么做", "策略", "方法", "头脑风暴"],
        "advise": ["建议", "推荐", "应该", "怎么办", "如何"],
        "design": ["设计", "产品", "用户体验", "ui", "交互"],
        "critique": [" critique", "批评", "问题", "缺点", "不足", "漏洞"],
        "case": ["案例", "例子", "实例", "故事", "经验"],
        "security": ["安全", "风险", "合规", "隐私", "保护"],
        "talent": ["人才", "团队", "招聘", "培养", "能力"],
        "budget": ["预算", "成本", "费用", "钱", "投入", "支出"],
    }

    for mode, keywords in keywords_map.items():
        if any(k in q for k in keywords):
            return mode

    return "explore"

