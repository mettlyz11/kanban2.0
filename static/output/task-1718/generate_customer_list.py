# ==================== 创建Excel文件 ====================
output_path = "/Users/mettlyz/.openclaw/workspace/output/task-1718/目标客户清单60家.xlsx"

with pd.ExcelWriter(output_path, engine='openpyxl') as writer:
    # 主表：全部客户
    df.to_excel(writer, sheet_name='全部客户清单', index=False)
    
    # 分表：高校/科研院所
    df_univ = df[df['客户分类'] == '高校/科研院所']
    df_univ.to_excel(writer, sheet_name='高校科研院所', index=False)
    
    # 分表：制药企业
    df_pharma = df[df['客户分类'] == '制药企业']
    df_pharma.to_excel(writer, sheet_name='制药企业', index=False)
    
    # 分表：材料企业
    df_material = df[df['客户分类'] == '材料企业']
    df_material.to_excel(writer, sheet_name='材料企业', index=False)
    
    # 获取workbook进行格式设置
    workbook = writer.book
    
    # 定义样式
    header_fill = PatternFill(start_color='4472C4', end_color='4472C4', fill_type='solid')
    header_font = Font(bold=True, color='FFFFFF', size=11)
    a_fill = PatternFill(start_color='FF6B6B', end_color='FF6B6B', fill_type='solid')
    b_fill = PatternFill(start_color='FFD93D', end_color='FFD93D', fill_type='solid')
    c_fill = PatternFill(start_color='6BCB77', end_color='6BCB77', fill_type='solid')
    center_align = Alignment(horizontal='center', vertical='center', wrap_text=True)
    border = Border(
        left=Side(style='thin'),
        right=Side(style='thin'),
        top=Side(style='thin'),
        bottom=Side(style='thin')
    )
    
    # 对每个sheet应用格式
    for sheet_name in workbook.sheetnames:
        worksheet = workbook[sheet_name]
        
        # 设置表头样式
        for cell in worksheet[1]:
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = center_align
            cell.border = border
        
        # 设置数据行样式和客户分级颜色标记
        for row in worksheet.iter_rows(min_row=2, max_row=worksheet.max_row):
            for cell in row:
                cell.alignment = center_align
                cell.border = border
                
                # 客户分级列着色（第7列）
                if cell.column == 7:
                    if cell.value == 'A':
                        cell.fill = a_fill
                    elif cell.value == 'B':
                        cell.fill = b_fill
                    elif cell.value == 'C':
                        cell.fill = c_fill
        
        # 调整列宽
        worksheet.column_dimensions['A'].width = 8   # 序号
        worksheet.column_dimensions['B'].width = 16  # 客户分类
        worksheet.column_dimensions['C'].width = 35  # 单位名称
        worksheet.column_dimensions['D'].width = 18  # 联系人
        worksheet.column_dimensions['E'].width = 18  # 联系方式
        worksheet.column_dimensions['F'].width = 20  # 预算区间
        worksheet.column_dimensions['G'].width = 10  # 客户分级
        worksheet.column_dimensions['H'].width = 40  # 决策链分析
        
        # 设置行高
        worksheet.row_dimensions[1].height = 25
        for i in range(2, worksheet.max_row + 1):
            worksheet.row_dimensions[i].height = 30

